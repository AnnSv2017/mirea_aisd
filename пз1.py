# 1 номер
# Импорт e
from math import e
# Функция, в которой нужно найти корень
def f(x):
  return e**(x-1)-x**3-x
# Отрезок, на котором лежит корень
l, r = 0, 1
# Пока не найдём корень, т.е. r примерно не будет равно l
while r-l>0.0001:
  # Серединка отрезка
  m = (l+r)/2
  # Значение функции в серединке
  fm = f(m)
  # Если серединка это корень, то заканчиваем цикл
  if fm==0:
    break
  # Если корень лежит левее серединки, то сдвигаем правую границу
  if f(l)*fm<0:
    r = m
  # Иначе, т.е. если корень правее серединки, то сдвигаем левую границу
  else:
    l = m
# Выводим ответ
print(m)

